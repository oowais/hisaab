#!/usr/bin/env python3
"""Generate the Hisaab app icon ("receipt") as Android resources + an SVG.

Run from anywhere: python3 src-tauri/android/icon/gen.py
Writes src-tauri/android/res/ (copied into the generated Android project by CI)
and src-tauri/android/icon/icon.svg (source for desktop PNG icons:
`vp exec tauri icon src-tauri/android/icon/icon.svg`).
A torn paper receipt, tilted, with the Timeline printed on it: three
subscription lanes and a diamond where a price changed. On desktop the
receipt itself is the icon (transparent around it); Android adaptive icons
need a full background, so it sits on marigold (terracotta at night).
Structure copied from Befikr's gen.py.
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
RES = HERE.parent / "res"

# Paper and print are the same in both themes; only the Android background changes.
COLORS = dict(paper="#FBF5EA", edge="#D8CBB5", top="#C49A5E", mid="#3B2A1A", low="#C49A5E", mark="#D2553F")
BACKGROUNDS = {"light": "#F0B85A", "dark": "#B5452F"}

# Receipt in a 108x108 canvas: x0, x1, top y, bottom y (where the teeth start), tooth depth.
PAPER = (30, 78, 22, 82, 6)
TEETH = 6
# (x0, x1, y, colour role, stroke width, alpha)
LANES = [
    (38, 54, 36, "top", 5.5, 1.0), (62, 70, 36, "top", 5.5, 1.0),
    (38, 70, 50, "mid", 6.5, 1.0),
    (46, 64, 64, "low", 5.5, 1.0),
    # The total line at the bottom of the slip.
    (38, 50, 75, "mid", 2.5, 0.45), (60, 70, 75, "mid", 2.5, 0.45),
]
MARK = (56, 50, 5.5)  # price-change diamond: cx, cy, half-diagonal
TILT = -8
SCALE = 0.66  # keep the tilted slip inside the 66dp safe circle
SVG_SCALE = 1.22  # desktop: no mask, so the slip fills the canvas
# Notification small icon: no safe circle, so the glyph fills ~85% of it.
STAT_SCALE = 1.2

def line(x0, x1, y):
    return f"M{x0},{y} L{x1},{y}"

def diamond(cx, cy, r):
    return f"M{cx},{cy - r} L{cx + r},{cy} L{cx},{cy + r} L{cx - r},{cy} Z"

def paper(dy=0):
    x0, x1, y0, y1, d = PAPER
    step = (x1 - x0) / (TEETH * 2)
    teeth = " ".join(
        f"L{x1 - step * i:g},{y1 + dy + (d if i % 2 else 0)}" for i in range(1, TEETH * 2 + 1)
    )
    return f"M{x0},{y0 + dy} L{x1},{y0 + dy} L{x1},{y1 + dy} {teeth} Z"

def vector(color_of, alpha_of, scale=SCALE):
    paths = [f'      <path android:pathData="{paper()}" android:fillColor="{color_of("paper")}" android:fillAlpha="{alpha_of("paper", 1.0)}"/>']
    paths += [
        f'      <path android:pathData="{line(x0, x1, y)}" android:strokeColor="{color_of(role)}" android:strokeAlpha="{alpha_of(role, a)}"\n'
        f'          android:strokeWidth="{w}" android:strokeLineCap="round"/>'
        for x0, x1, y, role, w, a in LANES
    ]
    cx, cy, r = MARK
    paths.append(
        f'      <path android:pathData="{diamond(cx, cy, r)}" android:fillColor="{color_of("mark")}" android:fillAlpha="{alpha_of("mark", 1.0)}"/>'
    )
    return (
        '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by src-tauri/android/icon/gen.py -->\n'
        '<vector xmlns:android="http://schemas.android.com/apk/res/android"\n'
        '    android:width="108dp" android:height="108dp" android:viewportWidth="108" android:viewportHeight="108">\n'
        f'  <group android:scaleX="{scale}" android:scaleY="{scale}" android:pivotX="54" android:pivotY="54">\n'
        f'    <group android:rotation="{TILT}" android:pivotX="54" android:pivotY="54">\n'
        + "\n".join(paths) + "\n    </group>\n  </group>\n</vector>\n"
    )

def svg_body(c=COLORS):
    body = f'<path d="{paper(2.5)}" fill="#3B2A1A" fill-opacity="0.18"/>'
    body += f'<path d="{paper()}" fill="{c["paper"]}" stroke="{c["edge"]}" stroke-width="0.8" stroke-linejoin="round"/>'
    body += "".join(
        f'<path d="{line(x0, x1, y)}" fill="none" stroke="{c[role]}" stroke-opacity="{a}" stroke-width="{w}" stroke-linecap="round"/>'
        for x0, x1, y, role, w, a in LANES
    )
    cx, cy, r = MARK
    body += f'<path d="{diamond(cx, cy, r + 2.2)}" fill="{c["paper"]}"/><path d="{diamond(cx, cy, r)}" fill="{c["mark"]}"/>'
    return f'<g transform="translate(54 54) scale({SVG_SCALE}) rotate({TILT}) translate(-54 -54)">{body}</g>'

def svg():
    return f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 108 108">{svg_body()}</svg>\n'

def write(rel, text):
    path = RES / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)

def main():
    for variant, folder in (("light", "values"), ("dark", "values-night")):
        colors = dict(bg=BACKGROUNDS[variant], **COLORS)
        write(f"{folder}/ic_launcher_colors.xml",
              '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by src-tauri/android/icon/gen.py -->\n<resources>\n'
              + "".join(f'  <color name="ic_launcher_{k}">{v}</color>\n' for k, v in colors.items()) + "</resources>\n")
    (HERE / "icon.svg").write_text(svg())
    write("drawable/ic_launcher_fg.xml", vector(lambda role: f"@color/ic_launcher_{role}", lambda role, a: a))
    # Monochrome (themed icons) and notification icon: one colour, so the
    # slip is faint and the print solid.
    write("drawable/ic_launcher_mono.xml",
          vector(lambda role: "#FF000000", lambda role, a: 0.35 if role == "paper" else max(a, 0.6)))
    write("drawable/ic_stat_hisaab.xml",
          vector(lambda role: "#FFFFFFFF", lambda role, a: 0.4 if role == "paper" else max(a, 0.7), STAT_SCALE))
    adaptive = ('<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by src-tauri/android/icon/gen.py -->\n'
                '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
                '  <background android:drawable="@color/ic_launcher_bg"/>\n'
                '  <foreground android:drawable="@drawable/ic_launcher_fg"/>\n'
                '  <monochrome android:drawable="@drawable/ic_launcher_mono"/>\n</adaptive-icon>\n')
    write("mipmap-anydpi-v26/ic_launcher.xml", adaptive)
    write("mipmap-anydpi-v26/ic_launcher_round.xml", adaptive)

if __name__ == "__main__":
    main()
